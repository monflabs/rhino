#!/usr/bin/env python3
"""Derives perf-gate tolerances from recordings of identical code.

Record the same engine several times (at least 8 JVMs; see benchmarks/README.md),
then run:

    python3 buildtools/perf-calibrate.py [--rounds 3] [--write <file>] <recording.json>...

For each metric, the gate's comparison is simulated many times by drawing two
disjoint groups of `rounds` recordings and comparing their medians, exactly as
perf-gate.sh does. The 99th percentile of the apparent regression is the noise
the gate must tolerate; the suggested band adds a 25% margin, rounded up to 5%,
with a 10% floor. --write saves the bands in the format PerfBenchmark reads
(benchmarks/testsrc/perf-tolerances.properties).
"""
import json
import math
import random
import sys
from collections import defaultdict


def main(argv):
    rounds = 3
    out = None
    if "--write" in argv:
        i = argv.index("--write")
        out = argv[i + 1]
        del argv[i:i + 2]
    if "--rounds" in argv:
        i = argv.index("--rounds")
        rounds = int(argv[i + 1])
        del argv[i:i + 2]
    samples = defaultdict(list)
    for path in argv:
        with open(path, encoding="utf-8") as f:
            for metric, value in json.load(f).items():
                samples[metric].append(value)
    if not samples or min(len(v) for v in samples.values()) < 2 * rounds:
        sys.exit(f"need at least {2 * rounds} recordings of every metric")

    rng = random.Random(42)
    bands = {}
    for metric, values in sorted(samples.items()):
        ratios = []
        for _ in range(5000):
            draw = rng.sample(values, 2 * rounds)
            base = sorted(draw[:rounds])[rounds // 2]
            head = sorted(draw[rounds:])[rounds // 2]
            ratios.append(head / base - 1)
        ratios.sort()
        p99 = ratios[int(len(ratios) * 0.99)]
        band = max(0.10, math.ceil(p99 * 1.25 * 20) / 20)
        bands[metric] = band
        print(f"{metric:45s} p99 {p99 * 100:6.1f}%  band {band * 100:4.0f}%")

    if out:
        with open(out, "w", encoding="utf-8") as f:
            f.write("# perf-gate tolerances: metric = allowed slowdown (fraction).\n")
            f.write(f"# Generated by buildtools/perf-calibrate.py from {len(argv)} recordings"
                    f" of identical code, {rounds} rounds per side.\n")
            for metric, band in bands.items():
                f.write(f"{metric}={band:.2f}\n")

    by_band = defaultdict(list)
    for metric, band in bands.items():
        by_band[band].append(metric)
    print("\nmetrics per band:")
    for band in sorted(by_band):
        print(f"  {band * 100:4.0f}%: {len(by_band[band])}")


if __name__ == "__main__":
    main(sys.argv[1:])
